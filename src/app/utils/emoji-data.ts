import { normalizeText } from "../../shared/text";

export interface EmojiEntry {
  /** The emoji itself (always a single grapheme). */
  e: string;
  /** Normalised Spanish + English search keywords. */
  k: string;
}

export const EMOJI_GROUP_IDS = [
  "smileys",
  "people",
  "nature",
  "food",
  "activities",
  "travel",
  "objects",
  "symbols",
  "flags",
] as const;

export type EmojiGroupId = (typeof EMOJI_GROUP_IDS)[number];

export interface EmojiGroup {
  id: EmojiGroupId;
  /** Emoji shown on the group's tab. */
  icon: string;
  emojis: EmojiEntry[];
}

export const EMOJI_GROUP_ICONS: Record<EmojiGroupId, string> = {
  smileys: "😀",
  people: "👋",
  nature: "🌳",
  food: "🍜",
  activities: "⚽",
  travel: "✈️",
  objects: "💡",
  symbols: "❤️",
  flags: "🏁",
};

interface GeneratedData {
  maxVersion: number;
  groups: Record<EmojiGroupId, [string, string][]>;
}

let loading: Promise<EmojiGroup[]> | null = null;

/**
 * The emoji dataset, generated by `scripts/generate-emoji-data.mjs`. It is a
 * separate chunk (~170 KB, ~50 KB gzipped) fetched the first time the picker
 * opens, so it never weighs on the initial page load.
 */
export function loadEmojiGroups(): Promise<EmojiGroup[]> {
  loading ??= import("./emoji-data.generated.json").then((mod) => {
    const data = (mod.default ?? mod) as unknown as GeneratedData;
    return EMOJI_GROUP_IDS.map((id) => ({
      id,
      icon: EMOJI_GROUP_ICONS[id],
      emojis: (data.groups[id] ?? []).map(([e, k]) => ({ e, k })),
    }));
  });
  // A failed chunk fetch (offline, deploy in between) must be retryable.
  loading.catch(() => {
    loading = null;
  });
  return loading;
}

const stripVariation = (s: string) => s.replace(/\uFE0F/g, "");

/** Emojis whose keywords contain every word of `query`, or that equal it. */
export function searchEmojis(
  groups: EmojiGroup[],
  query: string,
  limit = Infinity,
): EmojiEntry[] {
  const words = normalizeText(query).split(" ").filter(Boolean);
  if (!words.length) return [];
  const typed = stripVariation(query.trim());
  const out: EmojiEntry[] = [];
  for (const group of groups) {
    for (const entry of group.emojis) {
      if (stripVariation(entry.e) === typed || words.every((w) => entry.k.includes(w))) {
        out.push(entry);
        if (out.length >= limit) return out;
      }
    }
  }
  return out;
}
